import { AIProvider } from './AIProvider.js';

/**
 * Zero-dependency, zero-cost provider used when AI_PROVIDER=mock (the default).
 * It doesn't call any external API — it deterministically assembles a small,
 * genuinely working React + Tailwind project (and an Express backend, if the
 * prompt asks for one) by templating the user's prompt. This keeps the whole
 * product runnable/demoable with no OpenAI/Anthropic key at all, and gives a
 * concrete "shape" of what a real provider's JSON output should look like.
 */
export class MockProvider extends AIProvider {
  get name() {
    return 'mock';
  }

  async complete({ userPrompt, jsonSchema }) {
    const project = buildProjectFromPrompt(userPrompt);
    const text = jsonSchema ? JSON.stringify(project) : JSON.stringify(project, null, 2);
    return {
      text,
      usage: { promptTokens: estimateTokens(userPrompt), completionTokens: estimateTokens(text) },
    };
  }
}

function estimateTokens(str) {
  return Math.ceil((str || '').length / 4);
}

function titleCase(str) {
  return str.replace(/\b\w/g, (c) => c.toUpperCase());
}

function extractSiteName(prompt) {
  const quoted = prompt.match(/called\s+["']?([A-Za-z0-9 ]{2,40})["']?/i);
  if (quoted) return quoted[1].trim();
  const named = prompt.match(/named\s+["']?([A-Za-z0-9 ]{2,40})["']?/i);
  if (named) return named[1].trim();
  return 'My Website';
}

function detectNeedsBackend(prompt) {
  return /backend|api|node\.?js|express|database|contact form submission|login|auth|server/i.test(prompt);
}

function buildProjectFromPrompt(prompt) {
  const siteName = extractSiteName(prompt);
  const needsBackend = detectNeedsBackend(prompt);
  const isDark = /dark/i.test(prompt);
  const framework = needsBackend ? 'fullstack' : 'react';

  const files = [
    {
      path: 'frontend/src/App.jsx',
      content: `import Navbar from './components/Navbar';
import Hero from './components/Hero';
import About from './components/About';
import Contact from './components/Contact';
import Footer from './components/Footer';

export default function App() {
  return (
    <div className="min-h-screen ${isDark ? 'bg-slate-950 text-slate-100' : 'bg-white text-slate-900'}">
      <Navbar />
      <Hero />
      <About />
      <Contact />
      <Footer />
    </div>
  );
}
`,
    },
    {
      path: 'frontend/src/components/Navbar.jsx',
      content: `export default function Navbar() {
  return (
    <header className="flex items-center justify-between px-8 py-5 border-b ${isDark ? 'border-slate-800' : 'border-slate-200'}">
      <span className="text-lg font-semibold">${siteName}</span>
      <nav className="hidden md:flex gap-8 text-sm font-medium">
        <a href="#about" className="hover:opacity-70">About</a>
        <a href="#contact" className="hover:opacity-70">Contact</a>
      </nav>
    </header>
  );
}
`,
    },
    {
      path: 'frontend/src/components/Hero.jsx',
      content: `export default function Hero() {
  return (
    <section className="px-8 py-24 text-center max-w-3xl mx-auto">
      <h1 className="text-4xl md:text-5xl font-bold tracking-tight">Welcome to ${siteName}</h1>
      <p className="mt-4 text-lg opacity-80">Generated by WebForge AI from a natural-language prompt.</p>
      <a href="#contact" className="inline-block mt-8 px-6 py-3 rounded-lg bg-indigo-600 text-white font-medium hover:bg-indigo-700 transition-colors">Get in touch</a>
    </section>
  );
}
`,
    },
    {
      path: 'frontend/src/components/About.jsx',
      content: `export default function About() {
  return (
    <section id="about" className="px-8 py-16 max-w-3xl mx-auto">
      <h2 className="text-2xl font-semibold mb-3">About</h2>
      <p className="opacity-80 leading-relaxed">${siteName} was generated automatically. Describe changes in the AI panel — e.g. "make the hero blue" — and only the affected files will be updated.</p>
    </section>
  );
}
`,
    },
    {
      path: 'frontend/src/components/Contact.jsx',
      content: `import { useState } from 'react';

export default function Contact() {
  const [status, setStatus] = useState('idle');
  const [form, setForm] = useState({ name: '', email: '', message: '' });

  async function handleSubmit(e) {
    e.preventDefault();
    setStatus('loading');
    try {
      const res = await fetch('/api/contact', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(form),
      });
      if (!res.ok) throw new Error('Request failed');
      setStatus('success');
      setForm({ name: '', email: '', message: '' });
    } catch {
      setStatus('error');
    }
  }

  return (
    <section id="contact" className="px-8 py-16 max-w-xl mx-auto">
      <h2 className="text-2xl font-semibold mb-4">Contact</h2>
      <form onSubmit={handleSubmit} className="space-y-4">
        <input required placeholder="Name" value={form.name} onChange={(e) => setForm({ ...form, name: e.target.value })}
          className="w-full border rounded-lg px-4 py-2 ${isDark ? 'bg-slate-900 border-slate-700' : 'border-slate-300'}" />
        <input required type="email" placeholder="Email" value={form.email} onChange={(e) => setForm({ ...form, email: e.target.value })}
          className="w-full border rounded-lg px-4 py-2 ${isDark ? 'bg-slate-900 border-slate-700' : 'border-slate-300'}" />
        <textarea required placeholder="Message" value={form.message} onChange={(e) => setForm({ ...form, message: e.target.value })}
          className="w-full border rounded-lg px-4 py-2 h-28 ${isDark ? 'bg-slate-900 border-slate-700' : 'border-slate-300'}" />
        <button disabled={status === 'loading'} className="px-5 py-2 rounded-lg bg-indigo-600 text-white font-medium disabled:opacity-50">
          {status === 'loading' ? 'Sending…' : 'Send message'}
        </button>
        {status === 'success' && <p className="text-green-600 text-sm">Message sent — thank you!</p>}
        {status === 'error' && <p className="text-red-600 text-sm">Something went wrong. Please try again.</p>}
      </form>
    </section>
  );
}
`,
    },
    {
      path: 'frontend/src/components/Footer.jsx',
      content: `export default function Footer() {
  return (
    <footer className="px-8 py-8 text-center text-sm opacity-60 border-t ${isDark ? 'border-slate-800' : 'border-slate-200'}">
      © ${new Date().getFullYear()} ${siteName}. Built with WebForge AI.
    </footer>
  );
}
`,
    },
    {
      path: 'frontend/src/main.jsx',
      content: `import React from 'react';
import ReactDOM from 'react-dom/client';
import App from './App';
import './index.css';

ReactDOM.createRoot(document.getElementById('root')).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>
);
`,
    },
    {
      path: 'frontend/src/index.css',
      content: `@tailwind base;\n@tailwind components;\n@tailwind utilities;\n`,
    },
    {
      path: 'frontend/index.html',
      content: `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>${siteName}</title>
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/src/main.jsx"></script>
  </body>
</html>
`,
    },
    {
      path: 'frontend/package.json',
      content: JSON.stringify(
        {
          name: siteName.toLowerCase().replace(/\s+/g, '-'),
          private: true,
          version: '0.0.1',
          type: 'module',
          scripts: { dev: 'vite', build: 'vite build', preview: 'vite preview' },
          dependencies: { react: '^18.3.1', 'react-dom': '^18.3.1' },
          devDependencies: {
            '@vitejs/plugin-react': '^4.3.1',
            autoprefixer: '^10.4.19',
            postcss: '^8.4.38',
            tailwindcss: '^3.4.4',
            vite: '^5.3.1',
          },
        },
        null,
        2
      ),
    },
    {
      path: 'frontend/vite.config.js',
      content: `import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\n\nexport default defineConfig({ plugins: [react()], server: { proxy: { '/api': 'http://localhost:5100' } } });\n`,
    },
    {
      path: 'frontend/tailwind.config.js',
      content: `export default { content: ['./index.html', './src/**/*.{js,jsx}'], theme: { extend: {} }, plugins: [] };\n`,
    },
    {
      path: 'frontend/postcss.config.js',
      content: `export default { plugins: { tailwindcss: {}, autoprefixer: {} } };\n`,
    },
  ];

  if (needsBackend) {
    files.push(
      {
        path: 'backend/src/server.js',
        content: `import express from 'express';\nimport cors from 'cors';\nimport contactRoutes from './routes/contact.js';\n\nconst app = express();\napp.use(cors());\napp.use(express.json());\napp.use('/api/contact', contactRoutes);\n\nconst PORT = process.env.PORT || 5100;\napp.listen(PORT, () => console.log(\`Server running on port \${PORT}\`));\n`,
      },
      {
        path: 'backend/src/routes/contact.js',
        content: `import { Router } from 'express';\n\nconst router = Router();\n\nrouter.post('/', (req, res) => {\n  const { name, email, message } = req.body || {};\n  if (!name || !email || !message) {\n    return res.status(400).json({ success: false, message: 'name, email and message are required' });\n  }\n  // In production: persist to DB and/or send an email notification.\n  console.log('New contact submission:', { name, email });\n  res.status(201).json({ success: true, message: 'Message received' });\n});\n\nexport default router;\n`,
      },
      {
        path: 'backend/package.json',
        content: JSON.stringify(
          { name: 'backend', private: true, version: '0.0.1', type: 'module', scripts: { dev: 'node src/server.js' }, dependencies: { express: '^4.19.2', cors: '^2.8.5' } },
          null,
          2
        ),
      }
    );
  }

  files.push({
    path: 'README.md',
    content: `# ${siteName}\n\nGenerated by WebForge AI from the prompt:\n\n> ${prompt}\n\n## Run locally\n\n\`\`\`bash\ncd frontend && npm install && npm run dev\n${needsBackend ? '\ncd backend && npm install && npm run dev\n' : ''}\`\`\`\n`,
  });

  return {
    project: { name: siteName, description: `Generated from: ${prompt.slice(0, 140)}`, framework },
    files,
    dependencies: {},
    commands: needsBackend ? ['cd frontend && npm install', 'cd backend && npm install'] : ['cd frontend && npm install'],
    explanation: `Generated a ${framework} project called "${titleCase(siteName)}" with ${files.length} files based on your prompt.`,
  };
}
